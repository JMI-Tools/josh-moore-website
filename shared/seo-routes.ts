/** Union of every valid public route path, e.g. "/" | "/about" | ... */
export type RoutePath = (typeof SITE_ROUTES)[number]["path"];

/**
 * Build the canonical URL for a route path.
 * Root keeps its slash ("/"); every other path is emitted without a trailing slash.
 * `trailingSlash: false` in vercel.json makes the server agree: /about/ 308s to /about.
 */
export function canonicalUrl(path: string): string {
  const withSlash = path.startsWith("/") ? path : `/${path}`;
  if (withSlash === "/") return `${SITE_ORIGIN}/`;
  return `${SITE_ORIGIN}${withSlash.replace(/\/+$/, "")}`;
}

/** Look up a route's metadata. Throws on an unknown path rather than silently no-op. */
export function getRoute(path: RoutePath): RouteSeo {
  const route = SITE_ROUTES.find((r) => r.path === path);
  if (!route) {
    throw new Error(
      `[seo-routes] No entry for "${path}". Add it to SITE_ROUTES in shared/seo-routes.ts.`,
    );
  }
  return route;
}
