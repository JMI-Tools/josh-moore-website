/**
 * SINGLE SOURCE OF TRUTH for every public route on itsjoshmoore.com.
 *
 * Four things are derived from this one table, so they cannot drift apart:
 *
 *   1. client/src/App.tsx        — the wouter <Switch> is generated from it, and the
 *                                  component map is typed by `RoutePath`, so adding a
 *                                  route here without a page (or a page without an
 *                                  entry here) is a TypeScript error.
 *   2. client/src/hooks/useSeo   — `useRouteSeo("/about")` reads title/description
 *                                  from here for client-side navigation.
 *   3. dist/public/<file>        — scripts/prerender-seo.ts writes one real HTML file
 *                                  per route at build time, with this route's title,
 *                                  description, canonical and og tags baked into the
 *                                  source HTML (crawlers and link unfurlers do not run
 *                                  JavaScript, so the useSeo effect never fires for them).
 *   4. dist/public/sitemap.xml   — generated by the same script.
 *
 * Adding a public route = add one entry here + one line in App.tsx's PAGES map.
 * Nothing in vercel.json needs to change: Vercel's `cleanUrls` serves
 * dist/public/about.html at /about straight off the filesystem.
 */

